def generate_visual_quality_analysis():
    print("[*] Generating Visual Quality Analysis plots...")
    device = torch.device("cuda" if torch.cuda.is_available() else ("mps" if torch.backends.mps.is_available() else "cpu"))
    TASK_CONFIGS = {    
        "Task1_Baseline": {"skip": True,  "vae": False, "compress": False},
        # 👇 Just change compress to False on this line to match your latest actual weights 100%!
        "Task2_Ablation": {"skip": False, "vae": False, "compress": False}, 
        "Task3_VAE":      {"skip": True,  "vae": True,  "compress": False},
        "Task4_GAN_L1":   {"skip": True,  "vae": False, "compress": False},
        "Task5_GAN_L2":   {"skip": True,  "vae": False, "compress": False}
    }

    test_char = "永"  # Use the classic Yong character for final visual-quality comparison
    transform = transforms.Compose([transforms.ToTensor(), transforms.Normalize([0.5], [0.5])])
    src_img = render_char(test_char, Config.SOURCE_FONT)
    src_tensor = transform(src_img).unsqueeze(0).to(device)
    style_label = torch.tensor([0]).to(device) # Test style 0

    fig, axes = plt.subplots(1, 6, figsize=(18, 3))
    axes[0].imshow(src_img, cmap='gray'); axes[0].set_title("Source (GT)", fontweight='bold'); axes[0].axis('off')

    for idx, (task_name, cfg) in enumerate(TASK_CONFIGS.items()):
        ax = axes[idx + 1]
        weight_path = f"weights_{task_name}/generator_epoch_100.pth"
        
        if os.path.exists(weight_path):
            gen = AdvancedUNetGenerator(1, 1, 5, cfg['skip'], cfg['vae'], cfg['compress']).to(device)
            gen.load_state_dict(torch.load(weight_path, map_location=device))
            gen.eval()
            with torch.no_grad():
                fake, _ = gen(src_tensor, style_label)
            img = np.clip((fake.squeeze().cpu().numpy() * 0.5 + 0.5) * 255, 0, 255).astype(np.uint8)
            ax.imshow(img, cmap='gray')
            ax.set_title(task_name.split('_')[-1], fontsize=11, fontweight='bold')
        else:
            ax.text(0.5, 0.5, 'N/A', ha='center')
        ax.axis('off')

    plt.tight_layout()
    plt.savefig('Analysis_Plots/7_Supporting_Visual_Quality_Analysis.png', dpi=300)
    plt.close()
    print("[+] Visual comparison plots generated successfully.")

def generate_checkpoint_model_comparisons():
    print("[*] Generating checkpoint visual evolution across all five models...")
    os.makedirs('Analysis_Plots', exist_ok=True)

    device = torch.device("cuda" if torch.cuda.is_available() else ("mps" if torch.backends.mps.is_available() else "cpu"))
    task_configs = {
        "Task1_Baseline": {"label": "Baseline", "skip": True,  "vae": False, "compress": False},
        "Task2_Ablation": {"label": "Ablation", "skip": False, "vae": False, "compress": False},
        "Task3_VAE":      {"label": "VAE",      "skip": True,  "vae": True,  "compress": False},
        "Task4_GAN_L1":   {"label": "L1",       "skip": True,  "vae": False, "compress": False},
        "Task5_GAN_L2":   {"label": "L2",       "skip": True,  "vae": False, "compress": False},
    }
    checkpoint_outputs = {
        30: "Analysis_Plots/8_Factor7_Checkpoint_Epoch30_ModelComparison.png",
        60: "Analysis_Plots/9_Factor7_Checkpoint_Epoch60_ModelComparison.png",
        100: "Analysis_Plots/10_Factor7_Checkpoint_Epoch100_ModelComparison.png",
    }

    test_char = "永"
    transform = transforms.Compose([transforms.ToTensor(), transforms.Normalize([0.5], [0.5])])
    src_img = render_char(test_char, Config.SOURCE_FONT)
    src_tensor = transform(src_img).unsqueeze(0).to(device)
    style_label = torch.tensor([0], dtype=torch.long).to(device)

    for epoch, output_path in checkpoint_outputs.items():
        fig, axes = plt.subplots(1, 6, figsize=(18, 3))
        axes[0].imshow(src_img, cmap='gray')
        axes[0].set_title("Source (GT)", fontweight='bold')
        axes[0].axis('off')

        for idx, (task_name, cfg) in enumerate(task_configs.items(), start=1):
            ax = axes[idx]
            weight_path = f"weights_{task_name}/generator_epoch_{epoch}.pth"
            if os.path.exists(weight_path):
                torch.manual_seed(2575736)
                gen = AdvancedUNetGenerator(1, 1, 5, cfg['skip'], cfg['vae'], cfg['compress']).to(device)
                gen.load_state_dict(torch.load(weight_path, map_location=device))
                gen.eval()
                with torch.no_grad():
                    fake, _ = gen(src_tensor, style_label)
                img = np.clip((fake.squeeze().cpu().numpy() * 0.5 + 0.5) * 255, 0, 255).astype(np.uint8)
                ax.imshow(img, cmap='gray')
            else:
                ax.text(0.5, 0.5, 'N/A', ha='center', va='center')

            ax.set_title(cfg['label'], fontsize=11, fontweight='bold')
            ax.axis('off')

        fig.suptitle(f"Checkpoint Visual Evolution at {epoch}% Training Progress", fontsize=13, fontweight='bold')
        plt.tight_layout()
        plt.subplots_adjust(top=0.82)
        plt.savefig(output_path, dpi=300)
        plt.close()
        print(f"[+] Saved {output_path}")

